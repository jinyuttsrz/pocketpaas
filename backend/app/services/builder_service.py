"""项目类型识别与 Dockerfile 自动生成。

识别规则（按优先级）：
1. 已存在 Dockerfile → 直接复用（respect 用户意图），类型记为 custom
2. requirements.txt / pyproject.toml / *.py → python
3. package.json → node
4. index.html → static（用 nginx:alpine 托管）

生成策略保持"最小可用"：不强加 WSGI 服务器，Python 项目默认用 gunicorn，
若依赖里没有则回退 uvicorn，最终以用户 requirements 为准。
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

from app.core.config import settings
from app.services import compose_service

# 常见 Python 项目默认端口
PYTHON_DEFAULT_PORT = 8000
NODE_DEFAULT_PORT = 3000
STATIC_DEFAULT_PORT = 80

# 平台自动生成的 Dockerfile 首行标记：用于区分"用户自带"与"平台生成"。
# 带此标记的文件在重新构建时会按最新模板重新生成，不会被视为用户自定义。
GENERATED_MARKER = (
    "# Generated by PocketPaaS (auto) - do not edit, it is overwritten on rebuild."
)


def _pip_index_flag() -> str:
    """构建期 pip 源参数（配置了国内镜像时注入 -i）。"""
    return f"-i {settings.PIP_INDEX_URL} " if settings.PIP_INDEX_URL else ""


@dataclass
class ProjectProfile:
    """识别结果。"""

    project_type: str  # python / node / static / custom / compose
    has_dockerfile: bool
    default_port: int
    entry: str | None = None  # 推断出的入口模块（python: app.main:app 形式）
    compose: compose_service.ComposePlan | None = None  # 单服务 compose 解析结果


def _read_requirements(src: Path) -> str:
    req = src / "requirements.txt"
    return req.read_text(encoding="utf-8", errors="ignore").lower() if req.exists() else ""


def _guess_python_entry(src: Path) -> str:
    """推断 ASGI/WSGI 入口，返回 "module:attr" 形式。

    常见约定：app.py / main.py / wsgi.py 内的 app / application 变量。
    """
    candidates = ["main.py", "app.py", "application.py", "wsgi.py", "server.py"]
    for name in candidates:
        f = src / name
        if not f.exists():
            continue
        text = f.read_text(encoding="utf-8", errors="ignore")
        module = name[:-3]
        for attr in ("app", "application", "server"):
            # 匹配形如 `app = FastAPI(` / `app = Flask(` / `app = ...`
            if re.search(rf"^\s*{attr}\s*=", text, re.MULTILINE):
                return f"{module}:{attr}"
        return f"{module}:app"
    return "app:app"


def is_platform_generated(dockerfile: Path) -> bool:
    """判断 Dockerfile 是否由平台自动生成（首行带标记）。"""
    try:
        text = dockerfile.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return False
    return text.lstrip().startswith(GENERATED_MARKER)


# 上传包中可选的端口声明文件（显式覆盖），形如 {"port": 3000}
PORT_MANIFEST_NAMES = ("paas.json", ".paas.json")


def _port_from_manifest(src: Path) -> int | None:
    """读取上传包根目录的 paas.json / .paas.json 中的 port 字段。"""
    for name in PORT_MANIFEST_NAMES:
        f = src / name
        if not f.exists():
            continue
        try:
            data = json.loads(f.read_text(encoding="utf-8", errors="ignore"))
        except (json.JSONDecodeError, OSError):
            return None
        port = data.get("port") if isinstance(data, dict) else None
        # bool 是 int 的子类，需排除，避免 true/false 被当作端口
        if isinstance(port, int) and not isinstance(port, bool) and 1 <= port <= 65535:
            return port
    return None


def _port_from_dockerfile(src: Path) -> int | None:
    """解析用户自带 Dockerfile 的 EXPOSE 指令，取第一个合法端口。"""
    f = src / "Dockerfile"
    if not f.exists():
        return None
    text = f.read_text(encoding="utf-8", errors="ignore")
    for line in text.splitlines():
        m = re.match(r"\s*EXPOSE\s+(.+)", line, re.IGNORECASE)
        if not m:
            continue
        for token in m.group(1).split():
            token = token.split("/")[0]  # 去掉 /tcp、/udp 后缀
            if token.isdigit() and 1 <= int(token) <= 65535:
                return int(token)
    return None


@dataclass
class PortResolution:
    """自动识别到的容器端口及其依据。"""

    port: int
    source: str  # manifest / dockerfile / type_default


# 识别依据的中文说明：用于构建日志与前端提示，便于用户理解端口为何被改写
PORT_SOURCE_LABELS = {
    "manifest": "上传包内的 paas.json 声明",
    "compose": "docker-compose 的 ports / expose 声明",
    "dockerfile": "自带 Dockerfile 的 EXPOSE",
    "type_default": "项目类型默认端口",
}


def resolve_container_port(src: Path, profile: ProjectProfile) -> PortResolution | None:
    """自动推断容器端口，避免"用户填的端口"与"应用真实监听端口"不一致。

    优先级：
    1. 上传包内的 paas.json（显式声明 port，最可靠，也是唯一能覆盖 node 的手段）
    2. custom 类型 → 解析自带 Dockerfile 的 EXPOSE
    3. node 类型 → NODE_DEFAULT_PORT（平台无法向 Node 注入端口，只能按类型默认对齐）
    4. python / static → 返回 None（平台会把端口注入 uvicorn --port / nginx listen，
       用户填什么都能对齐，无需覆盖）

    返回 None 表示"平台无需覆盖，沿用调用方传入或应用已存的端口"。
    """
    manifest_port = _port_from_manifest(src)
    if manifest_port:
        return PortResolution(manifest_port, "manifest")
    if profile.compose is not None:
        if profile.compose.is_multi:
            public = profile.compose.public
            if public and public.container_port:
                return PortResolution(public.container_port, "compose")
        elif profile.compose.container_port:
            return PortResolution(profile.compose.container_port, "compose")
    if profile.project_type == "custom":
        port = _port_from_dockerfile(src)
        return PortResolution(port or PYTHON_DEFAULT_PORT,
                              "dockerfile" if port else "type_default")
    if profile.project_type == "node":
        return PortResolution(NODE_DEFAULT_PORT, "type_default")
    return None


def detect(src: Path, *, check_compose: bool = True) -> ProjectProfile:
    """识别项目类型。

    check_compose=False 用于 compose 构建上下文内部的类型识别，
    避免把上下文里的 compose 文件再次当作入口。
    """
    if not src.exists() or not src.is_dir():
        raise FileNotFoundError(f"源码目录不存在：{src}")

    if check_compose:
        compose_path = compose_service.find(src)
        if compose_path is not None:
            plan = compose_service.load(src, compose_path)
            if plan.is_multi:
                public = plan.public
                return ProjectProfile(
                    "compose",
                    any(spec.build_dockerfile for spec in plan.services),
                    (public.container_port if public else None) or PYTHON_DEFAULT_PORT,
                    compose=plan,
                )
            return ProjectProfile(
                "compose",
                bool(plan.build_dockerfile),
                plan.container_port or PYTHON_DEFAULT_PORT,
                compose=plan,
            )

    files = {p.name for p in src.iterdir()}
    dockerfile = src / "Dockerfile"

    # 用户自带的 Dockerfile → 复用（custom）；
    # 平台上一轮生成的（带标记）不算自带，需按最新模板重新生成，
    # 否则修正模板后重新构建不会生效。
    if dockerfile.exists() and not is_platform_generated(dockerfile):
        return ProjectProfile("custom", True, PYTHON_DEFAULT_PORT)

    if "package.json" in files:
        return ProjectProfile("node", False, NODE_DEFAULT_PORT)

    has_python = (
        "requirements.txt" in files
        or "pyproject.toml" in files
        or any(src.rglob("*.py"))
    )
    if has_python:
        return ProjectProfile(
            "python", False, PYTHON_DEFAULT_PORT, entry=_guess_python_entry(src)
        )

    if "index.html" in files or any(src.rglob("*.html")):
        return ProjectProfile("static", False, STATIC_DEFAULT_PORT)

    raise ValueError("无法识别项目类型：缺少 requirements.txt / package.json / index.html")


def _render_python(profile: ProjectProfile, port: int, requirements: str) -> str:
    """生成 Python 项目 Dockerfile。

    服务器按框架选择：Flask 等 WSGI 应用用 gunicorn；FastAPI 等 ASGI 应用用 uvicorn。
    """
    entry = profile.entry or "app:app"
    pip = _pip_index_flag()

    is_asgi = "fastapi" in requirements or "starlette" in requirements
    is_wsgi = ("flask" in requirements or "django" in requirements) and not is_asgi

    if is_wsgi:
        # WSGI：gunicorn 托管；依赖里没有则构建期补装
        install_server = "" if "gunicorn" in requirements else f" && pip install --no-cache-dir {pip}gunicorn"
        cmd = f'CMD ["gunicorn", "-b", "0.0.0.0:{port}", "{entry}"]'
    else:
        # ASGI：uvicorn 托管
        install_server = "" if "uvicorn" in requirements else f' && pip install --no-cache-dir {pip}"uvicorn[standard]"'
        cmd = f'CMD ["uvicorn", "{entry}", "--host", "0.0.0.0", "--port", "{port}"]'

    return f"""FROM python:3.12-slim

WORKDIR /app

# 先装依赖，利用镜像层缓存
COPY requirements.txt* ./
RUN if [ -f requirements.txt ]; then pip install --no-cache-dir {pip}-r requirements.txt; fi{install_server}

COPY . .

EXPOSE {port}
{cmd}
"""


def _render_node(port: int) -> str:
    registry = settings.NPM_REGISTRY
    return f"""FROM node:20-alpine

WORKDIR /app

COPY package*.json ./
RUN npm config set registry {registry} \\
    && (npm install --omit=dev || npm install)

COPY . .

EXPOSE {port}
CMD ["npm", "start"]
"""


def _render_static(port: int) -> str:
    """生成静态站点 Dockerfile（nginx:alpine 托管）。

    nginx 镜像自带的 default.conf 固定监听 80，而平台按 app.container_port
    建立 host → container 端口映射，二者必须一致，否则容器内无人监听、
    页面不可达。因此这里显式覆盖配置，让 nginx 监听平台分配的容器端口。
    """
    return f"""FROM nginx:alpine

COPY . /usr/share/nginx/html

# 覆盖镜像默认配置：默认固定监听 80，改为一律监听平台分配的容器端口
RUN printf '%s\\n' \\
    'server {{' \\
    '    listen {port};' \\
    '    location / {{' \\
    '        root /usr/share/nginx/html;' \\
    '        index index.html;' \\
    '    }}' \\
    '}}' > /etc/nginx/conf.d/default.conf

EXPOSE {port}
"""


def generate(src: Path, profile: ProjectProfile, container_port: int) -> str:
    """生成 Dockerfile 内容。

    custom（已有 Dockerfile）时返回原文，不做改动。
    """
    if profile.project_type == "custom":
        return (src / "Dockerfile").read_text(encoding="utf-8", errors="ignore")

    if profile.project_type == "python":
        return _render_python(profile, container_port, _read_requirements(src))
    if profile.project_type == "node":
        return _render_node(container_port)
    if profile.project_type == "static":
        return _render_static(container_port)
    raise ValueError(f"不支持的项目类型：{profile.project_type}")


def write_dockerfile(src: Path, content: str) -> Path:
    """将生成的 Dockerfile 写入源码目录。

    首行加平台标记，便于下次构建识别为"平台生成"并按最新模板覆盖。
    """
    path = src / "Dockerfile"
    text = (
        content
        if content.lstrip().startswith(GENERATED_MARKER)
        else f"{GENERATED_MARKER}\n{content}"
    )
    path.write_text(text, encoding="utf-8")
    return path
